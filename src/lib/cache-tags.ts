/**
 * 跨请求缓存的失效标签。
 *
 * 只有**营销页**(首页)用到跨请求缓存 —— 那是漏斗最顶端、匿名流量最大的一页,
 * 而它读的数据(已开放地区、院校列表、项目总数、起价)是月级别才变一次的。
 * 每个匿名访客都实打实查一次 RDS 没有意义。
 *
 * ⚠️ 字符串常量集中放这里,不要在各处手写。
 *    写缓存的地方和让它失效的地方一旦拼错一个字符,表现是
 *    「后台改了但前台不变」—— 而且不报错、看不出来,只能靠有人发现。
 *    集中之后拼错会直接编译不过。
 *
 * ⚠️ 标签失效只覆盖**后台页面上的操作**。命令行导入(npm run data:import /
 *    schools:import)跑在 Next 进程之外,调不到 revalidateTag。所以每个缓存
 *    另外带一个时间兜底(见 MARKETING_CACHE_SECONDS):标签管即时,TTL 管兜底。
 */
export const CACHE_TAGS = {
  /** 套餐(Plan)—— 首页「起价」 */
  plans: 'plans',
  /** 已开放地区 + 院校列表 + 项目总数 —— 首页的三个数字同源 */
  publicCatalog: 'public-catalog',
} as const

/**
 * 营销数据的兜底 TTL。
 *
 * 5 分钟是这么定的:后台任何一次改动都会立刻 revalidateTag,所以这个值
 * 只在**命令行导入**之后才起作用 —— 导完数据等最多 5 分钟首页数字才更新,
 * 对一个「收录院校 500 所」的展示数字完全可以接受。
 */
export const MARKETING_CACHE_SECONDS = 300
